"""Extract Beta radar symbols' original VWireData; leave the source files untouched."""
import hashlib
from pathlib import Path
import struct as S
from generate_station_lods import read_tree, child, crc

repo=Path(__file__).resolve().parents[1]
beta=Path('D:/games/Freelancer Beta/data/Interface/HUD')
models={'Planet':'HUD_radarplanet.3db','Capital':'HUD_radarcapship.3db',
        'Transport':'HUD_radartransport.3db','Dockable':'HUD_radardockable.3db',
        'Platform':'HUD_radarweaponplat.3db','TradeLane':'HUD_radarTLR.3db'}
out=['// Generated by tools/export_radar_symbols.py from the original Beta VWireData.',
     '#pragma once','namespace RadarSymbolsData {','struct Vertex {float x,y,z;};',
     'struct Mesh {Vertex const* vertices; unsigned short const (*edges)[2]; unsigned edgeCount;};']
for name,file in models.items():
    raw=(beta/file).read_bytes();root=read_tree(raw)[1][0]
    mesh=child(root,'VMeshLibrary').children[0]
    data=child(mesh,'VMeshData').blob
    flags,primitive,groups,indices,fvf,count=S.unpack_from('<II4H',data)
    assert (flags,primitive,fvf)==(1,4,2)
    offset=16+12*groups+2*indices
    assert len(data)==offset+12*count
    points=[S.unpack_from('<3f',data,offset+12*i) for i in range(count)]
    wire=child(child(root,'VMeshWire'),'VWireData').blob
    size,mesh_id,base,unique,n,maximum=S.unpack_from('<II4H',wire)
    assert size==16 and mesh_id==crc(mesh.name) and n%2==0 and len(wire)==16+2*n
    edges=S.unpack_from(f'<{n}H',wire,16)
    used=sorted(set(edges))
    assert len(used)==unique and max(edges)<maximum and base+maximum<=count
    radius=max((points[base+i][0]**2+points[base+i][1]**2)**.5 for i in used)
    assert radius>0
    remap={old:i for i,old in enumerate(used)}
    out.append(f'// {file}, SHA256 {hashlib.sha256(raw).hexdigest()}')
    out.append(f'inline constexpr Vertex {name}Vertices[]={{')
    for i in used:out.append('    {'+', '.join(f'{v/radius:.9f}f' for v in points[base+i])+'},')
    out.append('};')
    out.append(f'inline constexpr unsigned short {name}Edges[][2]={{')
    for i in range(0,n,2):out.append(f'    {{{remap[edges[i]]},{remap[edges[i+1]]}}},')
    out.append('};')
    out.append(f'inline constexpr Mesh {name}={{{name}Vertices,{name}Edges,{n//2}}};')
    if name=='Planet':
        # Convex silhouette of the actual Beta vertices, for a single translucent
        # fill without repeatedly blending the source's double-sided triangles.
        xy=sorted(set((points[base+i][0],points[base+i][1]) for i in used))
        def cross(a,b,c):return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])
        halves=[]
        for seq in (xy,list(reversed(xy))):
            half=[]
            for p in seq:
                while len(half)>1 and cross(half[-2],half[-1],p)<=0:half.pop()
                half.append(p)
            halves+=half[:-1]
        out.append('inline constexpr Vertex PlanetOutline[]={')
        for x,y in halves:out.append(f'    {{{x/radius:.9f}f,{y/radius:.9f}f,0}},')
        out.append('};')
    assert (beta/file).read_bytes()==raw
    print(f'{file}: {len(used)} vertices, {n//2} original edges')
out.append('}')
(repo/'src/freelancer/Client/radar_symbol_geometry.h').write_text('\n'.join(out)+'\n')
