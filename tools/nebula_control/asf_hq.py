"""Stage/apply ASF HQ native fog and mine relief opt-out, with verified rollback."""
import argparse
from datetime import datetime
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

from sphere_exterior import edit_section

ROOT = Path(__file__).resolve().parents[2]
GAME = Path('D:/games/FL_MOD')
OUT = ROOT/'src/obj/asf_hq'
FIELD = 'DATA/SOLAR/ASTEROIDS_MOD/asf_hq/m13_asf_right_field.ini'
VOLUME = 'DATA_EXTRA/VOLUMETRIC/volumetric.ini'
PAYLOAD = ('bin/freelancer.exe', 'bin/freelancer.pdb', FIELD, VOLUME)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def prepare():
    build = json.loads((OUT/'build.json').read_text())
    assert sha((GAME/'bin/freelancer.exe').read_bytes()) == build['baseline_client']
    assert sha((OUT/'freelancer.exe').read_bytes()) == build['client']
    assert sha((ROOT/'src/freelancer/Client/cli_asteroid.cpp').read_bytes()) == build['source']
    source = (ROOT/VOLUME).read_text(encoding='utf-8-sig')
    profiles = [m[0] for m in re.finditer(r'(?ims)^\[NebulaOverride\][^\n]*\n.*?(?=^\[|\Z)', source)
                if re.search(r'(?im)^file\s*=\s*m13_asf_hq_nebula\s*$', m[0])]
    assert len(profiles) == 1
    profile = profiles[0].strip()+'\n'
    # StorySystem reads asf_hq_dev directly; this field is a static shared DATA asset,
    # not generated by Pythonlancer. Confirm both source and generated system reference it.
    for name in ('asf_hq.ini', 'asf_hq_dev.ini'):
        text = (GAME/'DATA/UNIVERSE/SPECIAL/ASF_HQ'/name).read_text(encoding='utf-8-sig')
        assert r'file = solar\asteroids_mod\asf_hq\m13_asf_right_field.ini' in text
        assert r'file = solar\nebula_mod\m13_asf_hq_nebula.ini' in text
    manifest = {}
    for relative in PAYLOAD:
        original = (GAME/relative).read_bytes()
        if relative.startswith('bin/'):
            data = (OUT/Path(relative).name).read_bytes()
        else:
            text = original.decode('utf-8-sig').replace('\r\n', '\n')
            if relative == FIELD:
                text = edit_section(text, 'Field', None, {'contains_fog_zone':'1', 'rock_normals':'false'})
                assert text.count('asteroid = mine_radiate,') == 6
                assert re.search(r'(?im)^fill_dist\s*=\s*1000\s*$', text)
            else:
                assert not re.search(r'(?im)^file\s*=\s*m13_asf_hq_nebula\s*$', text), 'Profile already present; review before restaging'
                text = text.rstrip()+'\n\n'+profile
            newline = '\r\n' if b'\r\n' in original else '\n'
            data = text.replace('\n', newline).encode('utf-8')
            if original.startswith(b'\xef\xbb\xbf'):
                data = b'\xef\xbb\xbf'+data
        target = OUT/'staged'/relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        manifest[relative] = {'before':sha(original), 'after':sha(data)}
    (OUT/'manifest.json').write_text(json.dumps(manifest, indent=2))
    print('PASS: staged client + symbols, mine field and ASF-only volume override; Pythonlancer static field reference verified')


def apply():
    manifest = json.loads((OUT/'manifest.json').read_text())
    assert tuple(manifest) == PAYLOAD
    processes = subprocess.run(['tasklist','/FO','CSV','/NH'], capture_output=True, check=True).stdout.lower()
    for name in (b'freelancer.exe', b'freelancer_window.exe', b'freelancer_en.exe', b'freelancer_window_en.exe', b'flserver.exe'):
        assert b'"'+name+b'"' not in processes, 'Close Freelancer/FLServer before installation'
    for relative, item in manifest.items():
        assert sha((GAME/relative).read_bytes()) == item['before'], relative+' changed since preparation'
        assert sha((OUT/'staged'/relative).read_bytes()) == item['after']
    backup = OUT/('backup_'+datetime.now().strftime('%Y%m%d_%H%M%S_%f'))
    for relative, item in manifest.items():
        target = backup/relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(GAME/relative, target)
        assert sha(target.read_bytes()) == item['before']
    shutil.copy2(OUT/'manifest.json', backup/'manifest.json')
    touched = []
    try:
        for relative, item in manifest.items():
            touched.append(relative)
            shutil.copy2(OUT/'staged'/relative, GAME/relative)
            assert sha((GAME/relative).read_bytes()) == item['after']
    except Exception:
        for relative in reversed(touched):
            shutil.copy2(backup/relative, GAME/relative)
        raise
    print('Installed and hash-verified ASF HQ changes. Backup:', backup)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    apply() if parser.parse_args().apply else prepare()
