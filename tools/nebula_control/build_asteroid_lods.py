"""Offline UV-preserving LODs embedded in the client; no game DATA writes."""
from pathlib import Path
import ctypes as C,hashlib,json,struct,sys
import numpy as np
ROOT=Path(__file__).resolve().parents[2]
sys.path[:0]=[str(ROOT/'tools'),str(ROOT/'tools/nebula_control')]
from repair_panel_normals import leaves,triangles
OUT=ROOT/'out/graphics_settings/nebula_asteroid_mesh/lod'
HEADER=ROOT/'src/freelancer/Client/asteroid_lod_data.h'
def digest(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def fnv(data):
    h=14695981039346656037
    for b in data:h=((h^b)*1099511628211)&0xffffffffffffffff
    return h
def literal(f):
    s=format(f,'.9g')
    if '.' not in s and 'e' not in s:s+='.0'
    return s+'f'
def main():
    OUT.mkdir(parents=True,exist_ok=True);dll=ROOT/'bin/lod_meshopt.dll';d=C.CDLL(str(dll))
    d.simplify_lod.argtypes=[C.POINTER(C.c_uint),C.POINTER(C.c_uint),C.c_size_t,C.POINTER(C.c_float),C.c_size_t,C.POINTER(C.c_ubyte),C.c_size_t,C.c_float,C.POINTER(C.c_float)]
    d.simplify_lod.restype=C.c_size_t
    text=['// Generated by tools/nebula_control/build_asteroid_lods.py; original origin, normals and UV seams.','#pragma once','#include <cstdint>',
          'namespace AsteroidLodData {','struct Vertex {float pos[3],normal[3],uv[2];};',
          'struct Level {Vertex const* vertices;unsigned count;};','struct Model {std::uint64_t hash;Level levels[2];};']
    models=[];manifest={'models':[],'sources':{'tools/nebula_control/build_asteroid_lods.py':digest(Path(__file__))},'simplifier_sha256':digest(dll)}
    for letter in 'abc':
        p=Path(f'D:/Games/FL_MOD/DATA/SOLAR/ASTEROIDS_MOD/om15/ast_o15_nrml_{letter}.3db')
        blob=next(b for n,_,b in leaves(p.read_bytes())[1] if n.lower().endswith('/vmeshdata'))
        corners=triangles(blob)[2][0];unique=list(dict.fromkeys(corners));remap={v:i for i,v in enumerate(unique)}
        idx=(C.c_uint*len(corners))(*(remap[v] for v in corners));out=(C.c_uint*len(corners))()
        vin=(C.c_float*(len(unique)*9)).from_buffer_copy(b''.join(v+struct.pack('<f',0) for v in unique));locks=(C.c_ubyte*len(unique))()
        source_hash=fnv(b''.join(corners));entries=[]
        record={'source':str(p),'sha256':digest(p),'fingerprint':hex(source_hash),'native_triangles':len(corners)//3,'lods':[]}
        native=np.array([struct.unpack('<8f',v) for v in corners]);radius=np.linalg.norm(native[:,:3],axis=1).max()
        for number,target in enumerate((96,32)):
            error=C.c_float();n=d.simplify_lod(out,idx,len(corners),vin,len(unique),locks,target*3,.3,C.byref(error))
            assert n>0 and n%3==0 and n//3<= (100 if number==0 else 72)
            result=[unique[out[i]] for i in range(n)];vertices=np.array([struct.unpack('<8f',v) for v in result])
            tris=vertices[:,:3].reshape(-1,3,3);normals=np.cross(tris[:,1]-tris[:,0],tris[:,2]-tris[:,0])
            assert (np.linalg.norm(normals,axis=1)>1e-6).all()
            # Geometric closure across authored attribute seams; simplifier must not
            # open a hole while retaining the source UVs/normals on every corner.
            edges={}
            for tri in tris:
                for a,b in zip(tri,np.roll(tri,-1,axis=0)):
                    a,b=tuple(a),tuple(b);key=tuple(sorted((a,b)));edges.setdefault(key,[]).append((a,b))
            # Attribute seams can meet at a collapsed geometric edge. Every
            # directed edge must still have its opposite; no exposed boundary.
            assert all(len(v)%2==0 and sum(a<b for a,b in v)==len(v)//2 for v in edges.values()),letter
            name=f'{letter}{number}';text.append(f'inline constexpr Vertex {name}[]={{')
            for v in vertices:text.append('{{'+','.join(literal(x) for x in v[:3])+'},{'+','.join(literal(x) for x in v[3:6])+'},{'+','.join(literal(x) for x in v[6:])+'}},')
            text.append('};');entries.append('{'+name+','+str(n)+'}')
            (OUT/f'{name}.mesh').write_bytes(struct.pack('<I',n)+b''.join(result))
            record['lods'].append({'triangles':n//3,'attribute_error':error.value,'closed':True,
                'seam_edges_with_multiple_pairs':sum(len(v)>2 for v in edges.values()),'uv_corners_retained':True})
        models.append('{'+hex(source_hash)+'ull,{'+','.join(entries)+'}}');manifest['models'].append(record)
    text+=['inline constexpr Model Models[]={'+','.join(models)+'};',
           'inline std::uint64_t Fingerprint(void const* data,unsigned bytes){auto* p=static_cast<unsigned char const*>(data);std::uint64_t h=14695981039346656037ull;while(bytes--)h=(h^*p++)*1099511628211ull;return h;}',
           'inline Model const* Find(void const* vertices,unsigned bytes){auto h=Fingerprint(vertices,bytes);for(auto const& m:Models)if(m.hash==h)return &m;return nullptr;}','}']
    HEADER.write_text('\n'.join(text)+'\n');manifest['header_sha256']=digest(HEADER)
    (OUT/'geometry.json').write_text(json.dumps(manifest,indent=2));print(json.dumps(manifest['models'],indent=2))
if __name__=='__main__':main()
