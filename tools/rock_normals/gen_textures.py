"""Generate src/include/render/RockTextures.h: the diffuse textures that count as asteroid / debris
rock (docs/rock_normals.md). A material that uses one of them gets the rock relief shader, whatever
object it belongs to: an asteroid, a mining asteroid, or the rock parts of a station.

usage: python tools/rock_normals/gen_textures.py [DATA folder]   (default D:/games/FL_MOD/DATA)

Sources: every material of the asteroid-related .mat files plus any texture of any SOLAR .mat whose name
says rock / asteroid / debris. Ice, nomad, lair, dyson, planets and beasts are dropped: they keep
their own shaders. Names are lower case without .tga / .dds."""
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import generate_station_lods as gen  # noqa: E402

DATA = Path(sys.argv[1] if len(sys.argv) > 1 else 'D:/games/FL_MOD/DATA')
OUT = Path(__file__).resolve().parents[2] / 'src/include/render/RockTextures.h'

ASTEROID_MATS = ('ast_', 'asteroids_mod', 'n_mat', 'ku_tgk', 'dyn_debris', 'nrml')
NAME_KEYS = ('rock', 'asteroid', 'debris', 'obsid', 'lavastroid', 'tagaki', 'ast_sed', 'ast_dmg')
SKIP_FILES = ('ast_ice', 'ast_lair', 'ast_nomad', 'nomad', 'lair', 'dyson', 'beast', 'planet', 'fish')
SKIP_NAMES = ('nomad', 'lair', 'dyson', 'crystal', 'beast', 'planet', 'desert', 'rockdes', 'rockmnt', 'neutron_',
              'loot_', 'weapon_', 'new_gas')
SKIP_EXACT = ('neutron',)


def find(nodes, name):
    for n in nodes:
        if n.name.lower() == name:
            return n
        r = find(n.children, name)
        if r:
            return r


def text(node, key):
    c = [x for x in node.children if x.name == key]
    return c[0].blob.split(b'\0')[0].decode(errors='replace') if c and c[0].blob else ''


def ice_name(tex):
    """Ice textures (ice_carbon, ast_icecrystal2, "ice asteroid") keep the ice shader; pumice does not."""
    return re.search(r'(?<![a-z])ice', tex) is not None


def normal(name):
    name = name.strip().lower()
    name = re.sub(r'\.(tga|dds)$', '', name)
    return name


names = set()
for path in sorted((DATA / 'SOLAR').rglob('*.mat')):
    rel = path.relative_to(DATA).as_posix().lower()
    if any(s in rel for s in SKIP_FILES):
        continue
    try:
        _, roots = gen.read_tree(path.read_bytes())
    except Exception:
        continue
    lib = find(roots, 'material library')
    if not lib:
        continue
    whole_file = any(s in rel for s in ASTEROID_MATS)
    for m in lib.children:
        tex = normal(text(m, 'Dt_name'))
        if not tex or ice_name(tex) or any(s in tex for s in SKIP_NAMES) or tex in SKIP_EXACT:
            continue
        # Two names run together in a few materials ("a.tgab.tga"): keep the first.
        tex = re.split(r'\.(?:tga|dds)', tex)[0] if re.search(r'\.(tga|dds).', tex) else tex
        if whole_file or any(k in tex for k in NAME_KEYS):
            names.add(tex)

# Every asteroid archetype (static and dynamic) names the material libraries it draws with, and the
# fields only reference archetypes, so these libraries ARE the set the fields and the bases use.
# Libraries shared with stations or envmaps contribute rock-like texture names only.
PARTIAL_LIBS = ('dockable', 'envmap', 'dyson')
SKIP_LIBS = ('ice', 'nomad', 'lair', 'dyson', 'gas', 'planet')
libs = {}
for ini in ('asteroidarch.ini', 'dasteroidarch.ini'):
    body = (DATA / 'SOLAR' / ini).read_text(encoding='latin-1')
    for match in re.finditer(r'^\s*material_library\s*=\s*([^;\r\n]+)', body, re.M | re.I):
        libs.setdefault(match.group(1).strip().lower().replace(chr(92), '/'), 0)
        libs[match.group(1).strip().lower().replace(chr(92), '/')] += 1
skipped = {}
for lib_path, uses in sorted(libs.items()):
    path = DATA / lib_path
    if not path.is_file():
        continue
    try:
        _, roots = gen.read_tree(path.read_bytes())
    except Exception:
        continue
    lib = find(roots, 'material library')
    if not lib:
        continue
    skip_lib = any(s in lib_path for s in SKIP_LIBS)
    for m in lib.children:
        tex = normal(text(m, 'Dt_name'))
        if not tex:
            continue
        tex = re.split(r'\.(?:tga|dds)', tex)[0] if re.search(r'\.(tga|dds).', tex) else tex
        if skip_lib or ice_name(tex) or any(s in tex for s in SKIP_NAMES) or tex in SKIP_EXACT:
            skipped.setdefault(tex, lib_path)
        elif not any(s in lib_path for s in PARTIAL_LIBS) or any(k in tex for k in NAME_KEYS):
            names.add(tex)
print('asteroid archetype libraries:', len(libs))
print('left to their own shaders (ice / nomad / lair / dyson / gas / planet), by texture:')
for tex, lib_path in sorted(skipped.items()):
    if tex not in names:
        print('   %-28s %s' % (tex, lib_path))

names = sorted(names)
lines = ['#pragma once', '// Generated by tools/rock_normals/gen_textures.py: do not edit.',
         '// Diffuse textures of asteroid / debris rock (see docs/rock_normals.md). Lower case, no extension.',
         '#include <cstring>', '', 'inline bool RockTextureName(const char* Name)', '{',
         '    static const char* const Names[] = {']
lines += ['        "%s",' % n.replace('"', '') for n in names]
lines += ['    };', '    if (!Name) return false;', '    char Key[96];', '    unsigned Length = 0;',
          '    for (; Name[Length] && Length + 1 < sizeof(Key); ++Length)',
          '        Key[Length] = Name[Length] >= \'A\' && Name[Length] <= \'Z\' ? char(Name[Length] - \'A\' + \'a\') : Name[Length];',
          '    Key[Length] = \'\\0\';',
          '    if (Length > 4 && (!strcmp(Key + Length - 4, ".tga") || !strcmp(Key + Length - 4, ".dds"))) Key[Length - 4] = \'\\0\';',
          '    int Low = 0, High = int(sizeof(Names) / sizeof(Names[0])) - 1;',
          '    while (Low <= High)', '    {', '        const int Mid = (Low + High) / 2;', '        const int Order = strcmp(Key, Names[Mid]);',
          '        if (Order == 0) return true;', '        if (Order < 0) High = Mid - 1; else Low = Mid + 1;', '    }',
          '    return false;', '}', '']
OUT.write_text('\n'.join(lines), encoding='utf8')
print(len(names), 'textures ->', OUT)
for n in names:
    print(' ', n)
