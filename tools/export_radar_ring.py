"""Export the original Beta radar ring's native VWireData as renderer-free vectors.

The generated header embeds only normalized positions and the original line pairs;
no textures, materials or shared mesh libraries are loaded/replaced in the mod.
"""
import hashlib
from pathlib import Path
import struct as S
from generate_station_lods import read_tree, child, crc

repo = Path(__file__).resolve().parents[1]
source = Path('D:/games/Freelancer Beta/data/Interface/HUD/HUD_RadarRing.3db')
raw = source.read_bytes()
root = read_tree(raw)[1][0]
mesh = child(root, 'VMeshLibrary').children[0]
blob = child(mesh, 'VMeshData').blob
_, primitive, groups, indices, fvf, vertices = S.unpack_from('<II4H', blob)
assert primitive == 4 and fvf == 0x102
vb = 16 + 12 * groups + 2 * indices
points = [S.unpack_from('<3f', blob, vb + 20 * i) for i in range(vertices)]
wire = child(child(root, 'VMeshWire'), 'VWireData').blob
size, mesh_id, base, unique, count, maximum = S.unpack_from('<II4H', wire)
assert size == 16 and mesh_id == crc(mesh.name) and count % 2 == 0
edges = S.unpack_from(f'<{count}H', wire, 16)
assert len(wire) == 16 + count * 2 and max(edges) < maximum <= vertices
used = sorted(set(edges))
assert len(used) == unique
radius = max(abs(v[k]) for v in points for k in (0, 2))
remap = {old: new for new, old in enumerate(used)}
header = '// Generated by tools/export_radar_ring.py from Freelancer Beta HUD_RadarRing.3db.\n'
header += f'// Source SHA256: {hashlib.sha256(raw).hexdigest()}\n'
header += '#pragma once\nnamespace RadarRing\n{\nstruct Vertex { float x, y, z; };\n'
header += 'inline constexpr Vertex Vertices[] = {\n'
for index in used:
    header += '    {' + ', '.join(f'{v/radius:.9f}f' for v in points[base + index]) + '},\n'
header += '};\ninline constexpr unsigned short Edges[][2] = {\n'
for i in range(0, len(edges), 2):
    header += f'    {{{remap[edges[i]]}, {remap[edges[i+1]]}}},\n'
header += '};\n}\n'
(repo / 'src/freelancer/Client/radar_ring_geometry.h').write_text(header)
assert source.read_bytes() == raw
print(f'Exported {len(used)} vertices / {len(edges)//2} original ring edges, radius {radius:.9f}; source untouched.')
